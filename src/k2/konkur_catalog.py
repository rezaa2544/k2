def topics_for_course(course_name: str, group: str = "") -> tuple[str, ...]:
    """فهرست مبحثی یک درس؛ اگر ثبت نشده باشد خالی است.

    برای گروه «علوم ریاضی و فنی» نسخهٔ اختصاصی ریاضی/فیزیک/شیمی (کلید
    «…(ریاضی)») اولویت دارد؛ در غیر این صورت نسخهٔ پایه.
    """
    if group == "علوم ریاضی و فنی":
        specialized = TOPICS_BY_COURSE.get(f"{course_name} (ریاضی)")
        if specialized:
            return specialized
    if course_name in TOPICS_BY_COURSE:
        return TOPICS_BY_COURSE[course_name]
    for key, topics in TOPICS_BY_COURSE.items():
        if "(" in key:
            continue
        if key in course_name or course_name in key:
            return topics
    return ()


def catalog_topic_count() -> int:
    """تعداد مبحث‌های ثبت‌شده در کاتالوگ (برای پوشش)."""
    seen: set[str] = set()
    for key, topics in TOPICS_BY_COURSE.items():
        for topic in topics:
            seen.add(f"{key}|{topic}")
    return len(seen)


def subject_metadata(group: str, name: str) -> Optional[CourseRecord]:
    return next((course for course in courses_for_group(group) if course.name == name), None)


def is_official_exam_source_url(url: str) -> bool:
    """اعتبارسنجی دامنهٔ منبع اعلام‌شده؛ محتوای صفحه را تأیید نمی‌کند."""
    from urllib.parse import urlsplit

    try:
        parsed = urlsplit(url.strip())
        host = (parsed.hostname or "").lower().rstrip(".")
    except ValueError:
        return False
    if parsed.scheme.lower() not in {"http", "https"} or not host:
        return False
    if parsed.username is not None or parsed.password is not None:
        return False
    official_roots = ("sanjesh.org", "sccr.ir", "medu.gov.ir")
    return any(host == root or host.endswith("." + root) for root in official_roots)


