def transcript_courses_for_group(group: str) -> tuple[CourseRecord, ...]:
    if group not in EXAM_COURSES:
        return ()
    names = ["تعلیمات دینی", "فارسی عمومی", "زبان خارجی"]
    if group != "علوم انسانی":
        names.append("عربی عمومی")
    result: list[CourseRecord] = []
    for label, g10, g11, g12 in COMMON_GENERAL:
        if label in names:
            result.append(_transcript(label, (
                _book(label, g10[0], g10[1], 10),
                _book(label, g11[0], g11[1], 11),
                _book(label, g12[0], g12[1], 12),
            )))
    if "عربی عمومی" in names:
        result.append(_transcript("عربی عمومی", (
            _book("عربی عمومی", "عربی، زبان قرآن (1)", "110206", 10, "12211"),
            _book("عربی عمومی", "عربی، زبان قرآن (2)", "111206", 11),
            _book("عربی عمومی", "عربی، زبان قرآن (3)", "112206", 12),
        )))
    if group == "علوم انسانی":
        # این سه عنوان برای پایهٔ یازدهم در متن اطلاعیهٔ سال ۱۴۰۶ مشخص‌اند.
        result.extend((
            _transcript("عربی (2) — سابقهٔ یازدهم انسانی", (_book("عربی (2) — سابقهٔ یازدهم انسانی", "عربی، زبان قرآن (2) — انسانی", "111207", 11),), "تخصصی — سابقهٔ تحصیلی پایهٔ ۱۱"),
            _transcript("تاریخ (2) — سابقهٔ یازدهم انسانی", (_book("تاریخ (2) — سابقهٔ یازدهم انسانی", "تاریخ (2)", "111219", 11, "8196"),), "تخصصی — سابقهٔ تحصیلی پایهٔ ۱۱"),
            _transcript("جامعه‌شناسی (2) — سابقهٔ یازدهم انسانی", (_book("جامعه‌شناسی (2) — سابقهٔ یازدهم انسانی", "جامعه‌شناسی (2)", "111222", 11, "12349"),), "تخصصی — سابقهٔ تحصیلی پایهٔ ۱۱"),
        ))
    return tuple(result)


def courses_for_group(group: str) -> tuple[CourseRecord, ...]:
    return EXAM_COURSES.get(group, ()) + transcript_courses_for_group(group)


def catalog_books_for_selection(group: str, selected_names: set[str]) -> list[BookRecord]:
    result: list[BookRecord] = []
    seen: set[tuple[str, str, int]] = set()
    for course in courses_for_group(group):
        if course.name not in selected_names:
            continue
        for book in course.books:
            key = (book.code, book.title, book.grade)
            if key not in seen:
                seen.add(key)
                result.append(book)
    return result


