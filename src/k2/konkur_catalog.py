@dataclass(frozen=True)
class BookRecord:
    subject: str
    title: str
    code: str
    grade: int
    url: str = TEXTBOOKS_URL
    edition_year: Optional[int] = None
    status: str = "official_catalog_metadata_needs_page_crosscheck"
    relation: str = "منبع درسیِ درس؛ دامنهٔ دقیق فصل‌ها را اطلاعیهٔ مواد آزمون تعیین می‌کند"
    transcript_note: str = ""


@dataclass(frozen=True)
class CourseRecord:
    name: str
    course_type: str  # "تخصصی"، "عمومی" یا "سوابق تحصیلی"
    exam_coefficient: Optional[float] = None
    coefficient_status: str = "not_applicable"
    coefficient_source: str = ""
    books: tuple[BookRecord, ...] = ()
    note: str = ""


def _book(subject: str, title: str, code: str, grade: int, page_id: str = "", *, verified_1405: bool = False, transcript_note: str = "") -> BookRecord:
    url = f"https://chap.sch.ir/books/{page_id}" if page_id else TEXTBOOKS_URL
    return BookRecord(
        subject=subject,
        title=title,
        code=code,
        grade=grade,
        url=url,
        edition_year=1405 if verified_1405 else None,
        status=("official_page_metadata_1404_1405" if verified_1405 else "official_code_title_catalog_crosscheck_pending"),
        relation=(
            "پایهٔ دهم: کتابِ پایه‌ساز؛ در این فهرست سهم مستقیم در سوابق تحصیلی ۱۴۰۶ ادعا نمی‌شود."
            if grade == 10 else
            "کتاب متناظر با درس؛ شمول نهایی و محدودهٔ فصل‌ها تابع اطلاعیهٔ آزمون/دیپلم است."
        ),
        transcript_note=transcript_note,
    )


def _series(subject: str, titles: tuple[tuple[str, str], ...]) -> tuple[BookRecord, ...]:
    return tuple(_book(subject, title, code, grade) for grade, (title, code) in enumerate(titles, start=10))


def _exam(name: str, coefficient: int, books: tuple[BookRecord, ...], note: str = "") -> CourseRecord:
    return CourseRecord(
        name=name,
        course_type="تخصصی آزمون اختصاصی",
        exam_coefficient=float(coefficient),
        coefficient_status="official_notice_republished",
        coefficient_source=SANJESH_1406_URL,
        books=books,
        note=note or "ضریب مربوط به درسِ آزمون اختصاصی است؛ ضریب برنامه‌ریزیِ شخصی مستقل می‌ماند.",
    )


def _transcript(name: str, books: tuple[BookRecord, ...], course_type: str = "عمومی — سابقهٔ تحصیلی") -> CourseRecord:
    return CourseRecord(
        name=name,
        course_type=course_type,
        exam_coefficient=None,
        coefficient_status="no_exam_test_coefficient_transcript_weights_not_loaded",
        coefficient_source=SANJESH_1406_URL,
        books=books,
        note="این عنوان در اینجا مادهٔ آزمون تستی نیست؛ ضریب عددیِ هر درس از پیوست سوابق تحصیلی خوانده نشده است.",
    )


