def general_subject_note(course_name: str) -> str:
    """یادداشت صداقت یک درس عمومی (نبود داده را پنهان نمی‌کند)."""
    return GENERAL_SUBJECT_SYLLABUS.get(course_name, {}).get("note", "")


def general_grades(course_name: str) -> tuple[int, ...]:
    """پایه‌های یک درس عمومی؛ پیش‌فرض هر سه پایه."""
    return GENERAL_GRADES.get(course_name, (10, 11, 12))




def syllabus_for(course_name: str, grade: int | None = None) -> tuple[dict, ...]:
    """فصل‌های یک درس؛ اگر ``grade`` داده شود فقط همان پایه.

    درس‌های عمومی هم شامل می‌شوند: پایه‌ای که فهرست رسمی دارد برمی‌گردد و
    پایه‌ای که ندارد فهرست خالی می‌دهد (نه یک فصل فرضی با عدد جعلی).
    """
    by_grade = SYLLABUS_BY_COURSE.get(course_name)
    if by_grade is None:
        by_grade = GENERAL_SUBJECT_CHAPTERS.get(course_name, {})
    if grade is not None:
        return tuple(by_grade.get(int(grade), ()))
    return tuple(ch for chapters in by_grade.values() for ch in chapters)


def section_count(course_name: str, grade: int | None = None) -> int | None:
    """جمع گفتارهای شناخته‌شده؛ اگر هیچ‌کدام نامشخص باشد ``None``.

    فصل با گفتارهای نام‌دار: تعداد از روی خودِ فهرست. فصل فقط‌عددی: همان
    عدد. فصل نامشخص: هیچ سهمی ندارد.
    """
    total = 0
    known = False
    for ch in syllabus_for(course_name, grade):
        topics = ch.get("topics")
        sections = ch.get("sections")
        if topics:
            total += len(topics)
            known = True
        elif sections is not None:
            total += int(sections)
            known = True
    return total if known else None
